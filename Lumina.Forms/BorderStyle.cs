namespace Lumina.Forms;

/// <summary>
/// Specifies the border style for a control.
/// </summary>
public enum BorderStyle
{
    /// <summary>
    /// No border is drawn.
    /// </summary>
    None = 0,

    /// <summary>
    /// A single-line border is drawn.
    /// </summary>
    FixedSingle = 1,

    /// <summary>
    /// A sunken 3D border is drawn.
    /// </summary>
    Fixed3D = 2,
}
